function createEngine(THREE, RoomEnvironment) {
  const renderer = new THREE.WebGLRenderer({ canvas: cv, antialias: true, powerPreference: 'high-performance' });
  const DPR_MAX = TOUCH ? 1.5 : 2;
  renderer.setPixelRatio(Math.min(devicePixelRatio || 1, DPR_MAX));
  renderer.outputColorSpace = THREE.SRGBColorSpace;
  renderer.toneMapping = THREE.ACESFilmicToneMapping;
  renderer.toneMappingExposure = 1.05;
  renderer.shadowMap.enabled = true;
  renderer.shadowMap.type = THREE.PCFSoftShadowMap;

  const scene = new THREE.Scene();
  const pmrem = new THREE.PMREMGenerator(renderer);
  scene.environment = pmrem.fromScene(new RoomEnvironment(), 0.04).texture;
  scene.environmentIntensity = 0.35;

  // gradient sky dome: dark navy above (site palette) to a warm haze at the horizon
  const sky = new THREE.Mesh(new THREE.SphereGeometry(400, 32, 16), new THREE.ShaderMaterial({
    side: THREE.BackSide, depthWrite: false, fog: false,
    uniforms: { top: { value: new THREE.Color('#1d2433') }, mid: { value: new THREE.Color('#d9c6a0') }, bot: { value: new THREE.Color('#151b27') } },
    vertexShader: 'varying vec3 vP; void main(){ vP = normalize(position); gl_Position = projectionMatrix * modelViewMatrix * vec4(position,1.); }',
    fragmentShader: `uniform vec3 top, mid, bot; varying vec3 vP;
      void main(){ float h = vP.y; vec3 c = h > 0. ? mix(mid, top, pow(clamp(h*1.6,0.,1.), .7)) : mix(mid, bot, pow(clamp(-h*5.,0.,1.), .5));
      gl_FragColor = vec4(c, 1.); }`,
  }));
  scene.add(sky);

  const hemi = new THREE.HemisphereLight('#fff6e8', '#5b6474', 1.25); scene.add(hemi);
  const sun = new THREE.DirectionalLight('#ffe7c2', 2.1);
  sun.castShadow = true; sun.shadow.mapSize.set(TOUCH ? 1024 : 2048, TOUCH ? 1024 : 2048);
  sun.shadow.bias = -0.0004; sun.shadow.normalBias = 0.02;
  scene.add(sun, sun.target);

  // soft plinth under the floating model
  const plinthTex = (() => {
    const c = document.createElement('canvas'); c.width = c.height = 256; const g = c.getContext('2d');
    const gr = g.createRadialGradient(128, 128, 0, 128, 128, 128);
    gr.addColorStop(0, 'rgba(239,232,216,.16)'); gr.addColorStop(.6, 'rgba(239,232,216,.05)'); gr.addColorStop(1, 'rgba(239,232,216,0)');
    g.fillStyle = gr; g.fillRect(0, 0, 256, 256); const tx = new THREE.CanvasTexture(c); tx.colorSpace = THREE.SRGBColorSpace; return tx;
  })();
  const plinth = new THREE.Mesh(new THREE.PlaneGeometry(1, 1), new THREE.MeshBasicMaterial({ map: plinthTex, transparent: true, depthWrite: false }));
  plinth.rotation.x = -Math.PI / 2; plinth.position.y = -0.05; scene.add(plinth);

  const camera = new THREE.PerspectiveCamera(40, 1, 0.05, 1000);
  camera.rotation.order = 'YXZ';

  const matWall = new THREE.MeshStandardMaterial({ color: '#f3efe7', roughness: 0.92, metalness: 0 });
  const matCap = new THREE.MeshStandardMaterial({ color: '#2a2f38', roughness: 0.8 });
  const matGlass = new THREE.MeshStandardMaterial({ color: '#a9c4d3', roughness: 0.08, metalness: 0.1, transparent: true, opacity: 0.28, depthWrite: false, side: THREE.DoubleSide });
  const matRail = new THREE.MeshStandardMaterial({ color: '#30353d', roughness: 0.5, metalness: 0.6 });

  const group = new THREE.Group(); scene.add(group);
  let M = null;            // current model: {rects (m), size, center, spawn, floor, ceiling, mask, ...}
  let loadSeq = 0;

  /* ----- geometry ----- */
  function boxes(rects, h, withTop, y0 = 0) {
    // sides + top for a list of [x0,z0,x1,z1] boxes in metres; returns {side, top} BufferGeometries
    const sp = [], sn = [], tp = [], tn = [];
    const quad = (P, N, a, b, c, d, n) => { P.push(...a, ...b, ...c, ...a, ...c, ...d); for (let i = 0; i < 6; i++) N.push(...n); };
    for (const [x0, z0, x1, z1] of rects) {
      const y1 = y0 + h;
      quad(sp, sn, [x0, y0, z1], [x1, y0, z1], [x1, y1, z1], [x0, y1, z1], [0, 0, 1]);
      quad(sp, sn, [x1, y0, z0], [x0, y0, z0], [x0, y1, z0], [x1, y1, z0], [0, 0, -1]);
      quad(sp, sn, [x1, y0, z1], [x1, y0, z0], [x1, y1, z0], [x1, y1, z1], [1, 0, 0]);
      quad(sp, sn, [x0, y0, z0], [x0, y0, z1], [x0, y1, z1], [x0, y1, z0], [-1, 0, 0]);
      if (withTop) quad(tp, tn, [x0, y1, z1], [x1, y1, z1], [x1, y1, z0], [x0, y1, z0], [0, 1, 0]);
    }
    const mk = (P, N) => { const g = new THREE.BufferGeometry(); g.setAttribute('position', new THREE.Float32BufferAttribute(P, 3)); g.setAttribute('normal', new THREE.Float32BufferAttribute(N, 3)); return g; };
    return { side: mk(sp, sn), top: withTop ? mk(tp, tn) : null };
  }

  function loadImage(src) {
    return new Promise((res, rej) => { const im = new Image(); im.decoding = 'async'; im.onload = () => res(im); im.onerror = rej; im.src = src; });
  }
  function texFrom(img, maxSide) {
    let src = img;
    const s = Math.min(1, maxSide / Math.max(img.width, img.height));
    if (s < 1) { const c = document.createElement('canvas'); c.width = Math.round(img.width * s); c.height = Math.round(img.height * s); c.getContext('2d').drawImage(img, 0, 0, c.width, c.height); src = c; }
    const tx = new THREE.Texture(src); tx.needsUpdate = true; return tx;
  }

  function clearModel() {
    group.traverse(o => { if (o.geometry) o.geometry.dispose(); if (o.material && o.material.map) o.material.map.dispose(); if (o.material && o.material.alphaMap) o.material.alphaMap.dispose(); if (o.material && o.material.userData.own) o.material.dispose(); });
    group.clear(); M = null;
  }

  async function load(id) {
    const seq = ++loadSeq; const lay = LAYOUTS.find(l => l.id === id); if (!lay) return;
    view.classList.add('loading');
    let data, img, maskImg;
    try {
      [data, img, maskImg] = await Promise.all([
        fetch(url(`plans/walls/${id}.json`)).then(r => { if (!r.ok) throw new Error(r.status); return r.json(); }),
        loadImage(url(lay.plan2d)), loadImage(url(`plans/walls/${id}-mask.png`)),
      ]);
    } catch (e) { console.error('walk: load failed', e); view.classList.remove('loading'); return; }
    if (seq !== loadSeq) return;
    clearModel();

    const k = data.mpp, [bx0, by0, bx1, by1] = data.bounds;
    const cx = (bx0 + bx1) / 2, cy = (by0 + by1) / 2;
    const toM = (x, y) => [(x - cx) * k, (y - cy) * k];
    const R = r => { const [x0, z0] = toM(r[0], r[1]); const [x1, z1] = toM(r[0] + r[2], r[1] + r[3]); return [x0, z0, x1, z1]; };
    const walls = data.rects.map(R), edges = (data.edges || []).map(R);
    const W = data.w * k, H = data.h * k, ox = (data.w / 2 - cx) * k, oz = (data.h / 2 - cy) * k;
    const size = Math.max((bx1 - bx0) * k, (by1 - by0) * k);

    // floor = the plan drawing, trimmed by the footprint mask, tinted like pale oak
    const map = texFrom(img, TOUCH ? 2048 : 4096); map.colorSpace = THREE.SRGBColorSpace; map.anisotropy = Math.min(8, renderer.capabilities.getMaxAnisotropy());
    const alpha = new THREE.Texture(maskImg); alpha.needsUpdate = true;
    const floorMat = new THREE.MeshStandardMaterial({ map, alphaMap: alpha, alphaTest: 0.5, color: '#efe2cc', roughness: 0.85 }); floorMat.userData.own = true;
    const floor = new THREE.Mesh(new THREE.PlaneGeometry(W, H), floorMat);
    floor.rotation.x = -Math.PI / 2; floor.position.set(ox, 0, oz); floor.receiveShadow = true; group.add(floor);

    // ceiling (walk mode only): faces down, does not block the sun
    const ceilMat = new THREE.MeshStandardMaterial({ color: '#f6f3ee', roughness: 1, alphaMap: alpha, alphaTest: 0.5 }); ceilMat.userData.own = true;
    const ceil = new THREE.Mesh(new THREE.PlaneGeometry(W, H), ceilMat);
    ceil.rotation.x = Math.PI / 2; ceil.position.set(ox, WALL_H, oz); ceil.visible = false; group.add(ceil);

    const wg = boxes(walls, WALL_H, true);
    const wallMesh = new THREE.Mesh(wg.side, matWall); wallMesh.castShadow = wallMesh.receiveShadow = true;
    const capMesh = new THREE.Mesh(wg.top, matCap);
    const eg = boxes(edges, RAIL_H - 0.04, false);
    const glass = new THREE.Mesh(eg.side, matGlass); glass.renderOrder = 2;
    const rg = boxes(edges, 0.04, true, RAIL_H - 0.04);
    const rail = new THREE.Mesh(rg.side, matRail), railTop = new THREE.Mesh(rg.top, matRail);
    group.add(wallMesh, capMesh, glass, rail, railTop);

    // mask pixels for "is this point on the floor?"
    const mc = document.createElement('canvas'); mc.width = maskImg.width; mc.height = maskImg.height;
    const mctx = mc.getContext('2d', { willReadFrequently: true }); mctx.drawImage(maskImg, 0, 0);
    const mask = mctx.getImageData(0, 0, mc.width, mc.height).data;
    const onFloor = (x, z) => {
      const px = Math.floor((x / k + cx) / data.cell), py = Math.floor((z / k + cy) / data.cell);
      return px >= 0 && py >= 0 && px < mc.width && py < mc.height && mask[(py * mc.width + px) * 4] > 127;
    };

    // sun + shadow camera sized to the plan
    const sc = sun.shadow.camera, half = size * 0.62;
    sc.left = -half; sc.right = half; sc.top = half; sc.bottom = -half; sc.near = 1; sc.far = size * 4; sc.updateProjectionMatrix();
    sun.position.set(-size * 0.7, size * 1.2, size * 0.9); sun.target.position.set(0, 0, 0);
    plinth.scale.set(size * 2.4, size * 2.4, 1);

    const [sx, sz] = toM(data.spawn[0], data.spawn[1]);
    M = { walls: walls.concat(edges), size, onFloor, ceil, spawn: [sx, sz] };
    player.x = sx; player.z = sz; player.yaw = bestYaw(sx, sz); player.pitch = -0.05;
    doll.radius = fitRadius(); doll.target.set(0, 0, 0);
    if (mode === 'walk') { applyWalkCam(); ceil.visible = true; } else { intro(); }
    view.classList.remove('loading');
    kick();
  }

  /* ----- collision ----- */
  function collide(x, z) {
    for (let it = 0; it < 3; it++) {
      let moved = false;
      for (const [x0, z0, x1, z1] of M.walls) {
        const nx = Math.max(x0, Math.min(x, x1)), nz = Math.max(z0, Math.min(z, z1));
        const dx = x - nx, dz = z - nz, d2 = dx * dx + dz * dz;
        if (d2 < BODY_R * BODY_R) {
          if (d2 > 1e-9) { const d = Math.sqrt(d2), p = (BODY_R - d) / d; x += dx * p; z += dz * p; }
          else { // centre inside the box: push out along the shortest axis
            const l = x - x0 + BODY_R, r = x1 - x + BODY_R, u = z - z0 + BODY_R, b = z1 - z + BODY_R, m = Math.min(l, r, u, b);
            if (m === l) x = x0 - BODY_R; else if (m === r) x = x1 + BODY_R; else if (m === u) z = z0 - BODY_R; else z = z1 + BODY_R;
          }
          moved = true;
        }
      }
      if (!moved) break;
    }
    return [x, z];
  }
  function freeDist(x, z, a, max = 12) {
    const dx = Math.sin(a), dz = -Math.cos(a);
    for (let d = 0.2; d < max; d += 0.2) {
      const px = x + dx * d, pz = z + dz * d;
      if (!M.onFloor(px, pz)) return d;
      for (const [x0, z0, x1, z1] of M.walls) if (px > x0 && px < x1 && pz > z0 && pz < z1) return d;
    }
    return max;
  }
  function bestYaw(x, z) { let best = 0, bd = -1; for (let i = 0; i < 16; i++) { const a = i / 16 * Math.PI * 2, d = freeDist(x, z, a); if (d > bd) { bd = d; best = a; } } return best; }

  /* ----- cameras ----- */
  const doll = { theta: -0.6, phi: 0.95, radius: 20, target: new THREE.Vector3(), vt: 0, vp: 0 };
  const player = { x: 0, z: 0, yaw: 0, pitch: 0, vyaw: 0, vpitch: 0, goal: null, stuck: 0 };
  function fitRadius() {
    const vf = THREE.MathUtils.degToRad(camera.fov) / 2, hf = Math.atan(Math.tan(vf) * camera.aspect);
    return (M.size * 0.62) / Math.sin(Math.min(vf, hf)) ;
  }
  function dollPose(out = camera) {
    const { theta, phi, radius, target } = doll;
    out.position.set(target.x + radius * Math.sin(phi) * Math.sin(theta), target.y + radius * Math.cos(phi), target.z + radius * Math.sin(phi) * Math.cos(theta));
    out.lookAt(target);
  }
  function applyWalkCam() { camera.position.set(player.x, EYE, player.z); camera.rotation.set(player.pitch, player.yaw, 0, 'YXZ'); camera.rotation.y = -player.yaw; }

  // animated transitions
  let anim = null;
  function animateTo(endPos, endQuat, dur, done) {
    if (REDUCE) { camera.position.copy(endPos); camera.quaternion.copy(endQuat); done && done(); kick(); return; }
    anim = { p0: camera.position.clone(), q0: camera.quaternion.clone(), p1: endPos, q1: endQuat, t0: performance.now(), dur, done, lift: mode === 'walk' ? 0 : 0 };
    kick();
  }
  const dummy = new THREE.Object3D(); dummy.rotation.order = 'YXZ';
  function intro() {
    camera.fov = 40; camera.updateProjectionMatrix(); doll.radius = fitRadius();
    const end = new THREE.Object3D(); dollPose(end);
    if (REDUCE) { dollPose(); kick(); return; }
    const t0 = doll.theta; doll.theta = t0 - 0.9; doll.radius *= 1.35; dollPose(); doll.theta = t0; doll.radius /= 1.35;
    animateTo(end.position.clone(), end.quaternion.clone(), 1500);
  }

  function setMode(m) {
    if (!M || m === mode) return;
    mode = m; view.dataset.mode = m; renderText();
    cv.style.touchAction = m === 'walk' ? 'none' : 'pan-y';
    if (m === 'walk') {
      const p = M.onFloor(player.x, player.z) ? collide(player.x, player.z) : M.spawn; player.x = p[0]; player.z = p[1];
      dummy.position.set(player.x, EYE, player.z); dummy.rotation.set(player.pitch, -player.yaw, 0);
      M.ceil.visible = false;
      setFov(TOUCH && camera.aspect < 1 ? 78 : 66);
      animateTo(dummy.position.clone(), dummy.quaternion.clone(), 1400, () => { M.ceil.visible = true; });
    } else {
      M.ceil.visible = false; player.goal = null;
      setFov(40); doll.radius = fitRadius();
      const end = new THREE.Object3D(); dollPose(end);
      animateTo(end.position.clone(), end.quaternion.clone(), 1300);
    }
  }
  function setFov(f) { camera.fov = f; camera.updateProjectionMatrix(); }
  function zoom(dir) { if (mode !== 'over' || !M) return; doll.radius = THREE.MathUtils.clamp(doll.radius * (dir > 0 ? 1.18 : 0.85), M.size * 0.35, M.size * 3); if (!anim) dollPose(); kick(); }

  /* ----- input ----- */
  const ray = new THREE.Raycaster(), ndc = new THREE.Vector2(), plane = new THREE.Plane(new THREE.Vector3(0, 1, 0), 0), hit = new THREE.Vector3();
  function floorPoint(cx, cy) {
    const r = cv.getBoundingClientRect(); ndc.set((cx - r.left) / r.width * 2 - 1, -((cy - r.top) / r.height) * 2 + 1);
    ray.setFromCamera(ndc, camera); return ray.ray.intersectPlane(plane, hit) ? hit.clone() : null;
  }
  const pointers = new Map(); let drag = null, pinch0 = 0;
  cv.style.touchAction = 'pan-y';
  cv.addEventListener('pointerdown', e => {
    if (!M) return;
    pointers.set(e.pointerId, { x: e.clientX, y: e.clientY });
    cv.setPointerCapture(e.pointerId);
    if (pointers.size === 1) drag = { x: e.clientX, y: e.clientY, sx: e.clientX, sy: e.clientY, t: performance.now() };
    if (pointers.size === 2) { const [a, b] = [...pointers.values()]; pinch0 = Math.hypot(a.x - b.x, a.y - b.y); drag = null; }
    view.classList.add('grab');
  });
  cv.addEventListener('pointermove', e => {
    if (!pointers.has(e.pointerId) || !M) return;
    pointers.set(e.pointerId, { x: e.clientX, y: e.clientY });
    if (pointers.size === 2 && mode === 'over') {
      const [a, b] = [...pointers.values()], d = Math.hypot(a.x - b.x, a.y - b.y);
      if (pinch0) { doll.radius = THREE.MathUtils.clamp(doll.radius * pinch0 / d, M.size * 0.35, M.size * 3); pinch0 = d; if (!anim) dollPose(); kick(); }
      return;
    }
    if (!drag) return;
    const dx = e.clientX - drag.x, dy = e.clientY - drag.y; drag.x = e.clientX; drag.y = e.clientY;
    if (anim) return;
    if (mode === 'over') { doll.vt = -dx * 0.006; doll.vp = -dy * 0.004; doll.theta += doll.vt; doll.phi = THREE.MathUtils.clamp(doll.phi + doll.vp, 0.25, 1.35); dollPose(); }
    else { const s = TOUCH ? 0.005 : 0.0035; player.yaw += dx * s; player.pitch = THREE.MathUtils.clamp(player.pitch - dy * s, -1.2, 1.2); player.vyaw = dx * s; applyWalkCam(); }
    kick();
  });
  const up = e => {
    if (!pointers.has(e.pointerId)) return;
    pointers.delete(e.pointerId); if (pointers.size < 2) pinch0 = 0;
    view.classList.remove('grab');
    if (drag && pointers.size === 0 && e.type === 'pointerup') {
      const moved = Math.hypot(e.clientX - drag.sx, e.clientY - drag.sy), dt = performance.now() - drag.t;
      if (moved < 8 && dt < 450) tapAt(e.clientX, e.clientY);
      else if (mode === 'over' && !REDUCE) kick();
    }
    if (pointers.size === 0) drag = null;
  };
  cv.addEventListener('pointerup', up); cv.addEventListener('pointercancel', up);
  cv.addEventListener('wheel', e => {
    if (mode !== 'over' || !(e.ctrlKey || e.metaKey) || !M) return;   // plain wheel keeps scrolling the page
    e.preventDefault(); doll.radius = THREE.MathUtils.clamp(doll.radius * Math.exp(e.deltaY * 0.002), M.size * 0.35, M.size * 3); if (!anim) dollPose(); kick();
  }, { passive: false });

  function tapAt(x, y) {
    const p = floorPoint(x, y); if (!p || !M.onFloor(p.x, p.z)) return;
    if (mode === 'over') {
      const q = collide(p.x, p.z); player.x = q[0]; player.z = q[1];
      // look the way the camera was looking, toward the open space
      const look = Math.atan2(p.x - camera.position.x, -(p.z - camera.position.z));
      player.yaw = freeDist(q[0], q[1], look) > 1.2 ? look : bestYaw(q[0], q[1]); player.pitch = -0.05;
      setMode('walk');
    } else { player.goal = [p.x, p.z]; player.stuck = 0; kick(); }
  }

  // keyboard (only while walking and on screen)
  const keys = new Set();
  addEventListener('keydown', e => {
    if (mode !== 'walk' || !visible || e.target.closest && e.target.closest('input,textarea,select')) return;
    const k = e.key.toLowerCase();
    if (['w', 'a', 's', 'd', 'arrowup', 'arrowdown', 'arrowleft', 'arrowright', 'shift', 'q', 'e'].includes(k)) {
      keys.add(k); if (k.startsWith('arrow')) e.preventDefault(); player.goal = null; kick();
    }
  });
  addEventListener('keyup', e => keys.delete(e.key.toLowerCase()));
  addEventListener('blur', () => keys.clear());

  // joystick (touch)
  const stick = { x: 0, y: 0, id: null };
  joy.addEventListener('pointerdown', e => { stick.id = e.pointerId; joy.setPointerCapture(e.pointerId); moveStick(e); player.goal = null; });
  joy.addEventListener('pointermove', e => { if (e.pointerId === stick.id) moveStick(e); });
  const endStick = e => { if (e.pointerId !== stick.id) return; stick.id = null; stick.x = stick.y = 0; joy.firstElementChild.style.transform = ''; };
  joy.addEventListener('pointerup', endStick); joy.addEventListener('pointercancel', endStick);
  function moveStick(e) {
    const r = joy.getBoundingClientRect(), R = r.width / 2;
    let dx = e.clientX - (r.left + R), dy = e.clientY - (r.top + R); const d = Math.hypot(dx, dy), m = R * 0.62;
    if (d > m) { dx *= m / d; dy *= m / d; }
    stick.x = dx / m; stick.y = dy / m; joy.firstElementChild.style.transform = `translate(${dx}px,${dy}px)`; kick();
  }

  /* ----- loop: renders only while visible and something changes ----- */
  let raf = 0, last = 0, dirty = true;
  function kick() { dirty = true; if (!raf && visible) { last = performance.now(); raf = requestAnimationFrame(tick); } }
  function tick(now) {
    raf = 0; const dt = Math.min(0.05, (now - last) / 1000); last = now;
    let active = false;
    if (anim) {
      const u = Math.min(1, (now - anim.t0) / anim.dur), e = u < .5 ? 4 * u * u * u : 1 - Math.pow(-2 * u + 2, 3) / 2;
      camera.position.lerpVectors(anim.p0, anim.p1, e);
      if (mode === 'walk') camera.position.y += Math.sin(e * Math.PI) * 1.2;           // gentle arc while descending in
      camera.quaternion.slerpQuaternions(anim.q0, anim.q1, e);
      if (u >= 1) { const d = anim.done; anim = null; if (mode === 'walk') applyWalkCam(); else dollPose(); d && d(); }
      active = true;
    } else if (M && mode === 'walk') {
      let f = 0, s = 0, turn = 0;
      if (keys.has('w') || keys.has('arrowup')) f += 1;
      if (keys.has('s') || keys.has('arrowdown')) f -= 1;
      if (keys.has('a')) s -= 1; if (keys.has('d')) s += 1;
      if (keys.has('arrowleft') || keys.has('q')) turn -= 1; if (keys.has('arrowright') || keys.has('e')) turn += 1;
      if (stick.id !== null) { f -= stick.y; s += stick.x; }
      const run = keys.has('shift') ? 1.8 : 1;
      if (turn) { player.yaw += turn * 1.8 * dt; active = true; }
      let mx = 0, mz = 0;
      if (f || s) {
        const l = Math.max(1, Math.hypot(f, s)), sp = SPEED * run * dt / l;
        mx = (Math.sin(player.yaw) * f + Math.cos(player.yaw) * s) * sp;
        mz = (-Math.cos(player.yaw) * f + Math.sin(player.yaw) * s) * sp;
      } else if (player.goal) {
        const gx = player.goal[0] - player.x, gz = player.goal[1] - player.z, d = Math.hypot(gx, gz);
        if (d < 0.08) player.goal = null;
        else {
          const want = Math.atan2(gx, -gz); let da = want - player.yaw; da = Math.atan2(Math.sin(da), Math.cos(da));
          player.yaw += da * Math.min(1, dt * 5);
          const sp = Math.min(d, SPEED * dt * (Math.abs(da) > 1.2 ? 0.3 : 1)); mx = gx / d * sp; mz = gz / d * sp;
        }
      }
      if (mx || mz) {
        const [nx, nz] = collide(player.x + mx, player.z + mz);
        const prog = Math.hypot(nx - player.x, nz - player.z);
        player.x = nx; player.z = nz; active = true;
        if (player.goal) { player.stuck = prog < SPEED * dt * 0.2 ? player.stuck + dt : 0; if (player.stuck > 0.35) player.goal = null; }
      }
      if (player.goal) active = true;
      if (active) applyWalkCam();
    } else if (M && mode === 'over' && !drag && !REDUCE && (Math.abs(doll.vt) > 1e-4 || Math.abs(doll.vp) > 1e-4)) {
      doll.theta += doll.vt; doll.phi = THREE.MathUtils.clamp(doll.phi + doll.vp, 0.25, 1.35);
      doll.vt *= 0.9; doll.vp *= 0.9; dollPose(); active = true;
    }
    if (dirty || active) { renderer.render(scene, camera); dirty = false; }
    if ((active || stick.id !== null || keys.size) && visible) raf = requestAnimationFrame(tick);
  }

  function resize() {
    const w = cv.clientWidth, h = cv.clientHeight; if (!w || !h) return;
    renderer.setSize(w, h, false); camera.aspect = w / h; camera.updateProjectionMatrix();
    if (M && mode === 'over' && !anim) { doll.radius = fitRadius(); dollPose(); }
    kick();
  }
  new ResizeObserver(resize).observe(cv); resize();

  function setVisible(v) { visible = v; if (v) kick(); else if (raf) { cancelAnimationFrame(raf); raf = 0; } }

  if (/[?&]walkdebug/.test(location.search)) window.__walk = { THREE, scene, camera, renderer, group, doll, player, kick, get M() { return M; } };
  return { load: id => { load(id); }, setMode, zoom, resize, setVisible };
}
